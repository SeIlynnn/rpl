-- 1. TABEL MATERIALS
CREATE TABLE IF NOT EXISTS public.materials (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "no" INTEGER,
  item_id INTEGER,
  nama_item TEXT NOT NULL,
  rarity INTEGER DEFAULT 1,
  item_type TEXT,
  item_drop TEXT,
  object_drop TEXT,
  persentase REAL,
  image_path TEXT
);

-- 2. TABEL ARMORS
CREATE TABLE IF NOT EXISTS public.armors (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "no" INTEGER,
  item_id INTEGER,
  nama_item TEXT NOT NULL,
  rarity INTEGER DEFAULT 1,
  type TEXT,
  stats TEXT,
  skill TEXT,
  image_path TEXT
);

-- 3. TABEL MONSTERS
CREATE TABLE IF NOT EXISTS public.monsters (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "no" INTEGER,
  nama TEXT NOT NULL,
  title TEXT,
  habitat TEXT,
  classification TEXT,
  imun_to TEXT,
  item_drop TEXT,
  max_health TEXT,
  def TEXT,
  size TEXT,
  image_path TEXT
);

-- 4. TABEL WEAPONS
CREATE TABLE IF NOT EXISTS public.weapons (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "no" INTEGER,
  item_id INTEGER,
  nama_item TEXT NOT NULL,
  rarity INTEGER DEFAULT 1,
  role TEXT,
  normal_stats TEXT,
  negative_stats TEXT,
  skill_aktif TEXT,
  image_path TEXT
);

-- 5. TABEL CHARMS
CREATE TABLE IF NOT EXISTS public.charms (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "no" INTEGER,
  item_id INTEGER,
  nama_item TEXT NOT NULL,
  rarity INTEGER DEFAULT 1,
  stats TEXT,
  image_path TEXT
);

-- 6. TABEL ANIMALS
CREATE TABLE IF NOT EXISTS public.animals (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "no" INTEGER,
  item_id INTEGER,
  nama TEXT NOT NULL,
  total_hp INTEGER,
  habitat TEXT,
  item_drop TEXT,
  image_path TEXT
);

